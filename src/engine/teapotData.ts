/**
 * The Utah Teapot — the 1976 version (Jim Blinn's 3/4 vertical scaling of Martin
 * Newell's 1975 patches): 28 bicubic Bézier patches, 16 control points each, in
 * the model's ORIGINAL frame — z up, rim at z = 2.25, spout toward +x, handle
 * toward -x, mirror plane y = 0. `teapotGeometry.ts` turns it into the preview's
 * y-up, centred, 1.6-unit frame.
 *
 * PROVENANCE. Recovered 2026-09-05 from the official Utah Teapot page
 * (https://graphics.cs.utah.edu/teapot/ — Cem Yuksel, University of Utah), whose
 * generator tessellates the historical patch data client-side and offers an OBJ
 * download but publishes no control-point file. Its "Patch Coordinates" texture
 * layout exposes each patch's parameter grid, so the 1976 mesh was generated at
 * resolution 8 (81 exact surface samples per patch), the 16 control points solved
 * per patch by least squares — a bicubic is determined by far fewer — and the fit
 * checked: worst residual 4.35e-7 (float32 noise), every recovered coordinate one
 * of Newell's own rationals (0.784, 1.4375, 2.34375, …), snapped here to 5 dp.
 * `uv` is that page's "Bijective Layout" (texture mode 3), which the same fit
 * showed to be EXACTLY affine per patch (residual 4.5e-8): u = ou + su·s and
 * v = ov + sv·t', where t' is the patch parameter t remapped per column by a
 * cubic Bézier whose control values are the normalized cumulative chord
 * lengths of that column's control polygon in the UNSCALED 1975 frame — see
 * `columnRemap` in teapotGeometry.ts for the derivation (exact to 7e-7 over
 * every sampled column; arc length and chord length were each ~0.13 off).
 * Chart rectangles are disjoint and lie inside [0,1]²; v never goes below 0.15
 * because that band is where later versions put the bottom the 1976 teapot
 * does not have.
 *
 * TERMS (verbatim from the page): "The Utah Teapot model files are freely
 * available for any use, including commercial use. To preserve the historical
 * identity and provenance of the model, users are requested to identify the model,
 * and any substantially derived version of it, as a Utah Teapot (or Modified Utah
 * Teapot) and to acknowledge its origin as the historic Utah Teapot developed at
 * the University of Utah." — which every emitted OBJ header and the preview's
 * Model menu do.
 */

export interface TeapotPatch {
  /** 16 control points × xyz, index (i * 4 + j) * 3 + c — i along s, j along t. */
  readonly cp: readonly number[];
  /** Bijective-layout chart: [su, ou, sv, ov] → u = ou + su·s, v = ov + sv·t'. */
  readonly uv: readonly [number, number, number, number];
}

